function base64ToArrayBuffer(base64) {
    let binary_string = window.atob(base64);
    let len = binary_string.length;
    let bytes = new Uint8Array(len);
    for (let i = 0; i < len; i++) {
        bytes[i] = binary_string.charCodeAt(i);
    }
    return bytes.buffer;
}

function getOriginalName(name) {
    let base = name.substring(name.lastIndexOf('/') + 1).trim();
    if (base.includes(' - ')) {
        return base.split(' - ')[0].trim();
    }
    return base;
}

function saveImportedBlob(filePath, blob) {
    StorageManager.saveFromServer(filePath, blob).then(async () => {
        alert("Skylander imported successfully!");
        await StorageManager.init();
    }).catch(err => {
        alert("Error during import: " + err);
    });
}

window.scanQR = function() {
    if (!window.cordova || !cordova.plugins || !cordova.plugins.barcodeScanner) {
        alert("Barcode scanner not available. Run the app on a real device or install the plugin.");
        return;
    }
    
    // Ensure StorageManager is ready before scanning
    if (!StorageManager.fileList || StorageManager.fileList.length === 0) {
        StorageManager.init();
    }
    
    cordova.plugins.barcodeScanner.scan(
        function (result) {
            if (result.cancelled) return;
            
            const text = result.text;
            if (!text || !text.includes('|')) {
                alert("Invalid QR code. Ensure it is a Skylander generated by the app.");
                return;
            }
            
            const parts = text.split('|');
            let fileName, base64Data, isZipped = false;
            
            if (parts.length === 3 && parts[1] === 'zip') {
                fileName = parts[0];
                base64Data = parts[2];
                isZipped = true;
            } else {
                fileName = parts[0];
                base64Data = parts[1];
            }
            
            try {
                let buffer = base64ToArrayBuffer(base64Data);
                
                if (isZipped) {
                    const compressedUint8 = new Uint8Array(buffer);
                    const decompressed = pako.inflate(compressedUint8);
                    buffer = decompressed.buffer;
                }
                
                const blob = new Blob([buffer], { type: 'application/octet-stream' });
                
                let baseFileName = fileName.replace('.dump', '').replace(/\uFFFD/g, "'").trim();
                let originalName = getOriginalName(baseFileName);
                
                const choice = confirm(`You received: ${baseFileName}\nDo you want to save it as a clone?\n\nPress OK to create a Clone, or Cancel to overwrite your version.`);
                
                const shareFiles = StorageManager.fileList;
                if (choice) {
                    let suffix = prompt("Enter a name (suffix) for the clone:", "Trade");
                    if (!suffix) return;
                    let cloneName = originalName + " - " + suffix + ".dump";
                    
                    const existingItem = shareFiles.find(f => getOriginalName(f.replace('.dump','').replace(/\uFFFD/g,"'").trim()) === originalName && !f.includes(' - '));
                    let savePath;
                    if (existingItem) {
                        let parts2 = existingItem.split('/');
                        parts2.pop();
                        savePath = parts2.join('/') + '/' + cloneName;
                    } else {
                        savePath = "SkylandersDump/Shared/" + cloneName;
                    }
                    
                    saveImportedBlob(savePath, blob);
                } else {
                    const matches = shareFiles.filter(f => getOriginalName(f.replace('.dump','').replace(/\uFFFD/g,"'").trim()) === originalName);
                    if (matches.length === 0) {
                        let savePath = "SkylandersDump/Shared/" + fileName;
                        saveImportedBlob(savePath, blob);
                    } else if (matches.length === 1) {
                        if(confirm(`Are you sure you want to overwrite: ${matches[0].split('/').pop()}?`)) {
                            saveImportedBlob(matches[0], blob);
                        }
                    } else {
                        let listStr = matches.map((m, i) => `${i+1}: ${m.split('/').pop()}`).join('\n');
                        let pick = prompt(`Which version do you want to overwrite?\n\n${listStr}\n\nEnter the number:`);
                        if (pick) {
                            let idx = parseInt(pick) - 1;
                            if (idx >= 0 && idx < matches.length) {
                                saveImportedBlob(matches[idx], blob);
                            }
                        }
                    }
                }
            } catch(e) {
                console.error(e);
                alert("Error during QR data extraction.");
            }
        },
        function (error) {
            alert("Scan failed: " + error);
        },
        {
            preferFrontCamera : false, 
            showFlipCameraButton : true, 
            showTorchButton : true, 
            torchOn: false, 
            saveHistory: false,
            prompt : "Scan the Skylander QR Code", 
            resultDisplayDuration: 500, 
            formats : "QR_CODE",
            disableAnimations : true,
            disableSuccessBeep: false
        }
    );
};
